import { afterEach, expect, test } from 'bun:test';
import { mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { assertReplaceableOutput, outputRoot, ROOT_DIR } from './output.ts';
import { writeManifest } from './deployment.ts';

const temporary: string[] = [];
function directory() {
  const root = mkdtempSync(join(realpathSync(tmpdir()), 'site-output-'));
  temporary.push(root);
  return root;
}
afterEach(() => { for (const path of temporary.splice(0)) rmSync(path, { recursive: true, force: true }); });

function previousSite(root: string) {
  for (const path of ['index.html', 'index.md', 'llms.txt', 'CNAME']) writeFileSync(join(root, path), path);
  writeManifest(root);
}

test('new/empty destinations and recorded generated sites are replaceable without matching current bytes', () => {
  const root = directory();
  expect(() => assertReplaceableOutput(join(root, 'new'))).not.toThrow();
  expect(() => assertReplaceableOutput(root)).not.toThrow();
  previousSite(root);
  writeFileSync(join(root, 'index.html'), 'changed generated bytes');
  rmSync(join(root, 'index.md'));
  expect(() => assertReplaceableOutput(root)).not.toThrow();
});

test('invalid markers and unrelated valid file manifests do not authorize removal', () => {
  const root = directory();
  writeFileSync(join(root, 'source.txt'), 'preserve');
  writeFileSync(join(root, 'deployment-manifest.json'), '{}');
  expect(() => assertReplaceableOutput(root)).toThrow('valid generated-site manifest');
  writeManifest(root); // A valid generic file digest is not a recognizable generated site.
  expect(() => assertReplaceableOutput(root)).toThrow('does not identify a generated site');
  expect(readFileSync(join(root, 'source.txt'), 'utf8')).toBe('preserve');
});

test('checkout roots, worktree .git files and .git paths are refused even with a generated marker', () => {
  const root = directory();
  previousSite(root);
  for (const kind of ['directory', 'worktree-file']) {
    const marker = join(root, '.git');
    if (kind === 'directory') mkdirSync(marker);
    else writeFileSync(marker, 'gitdir: opaque-test-fixture');
    expect(() => assertReplaceableOutput(root)).toThrow('checkout');
    expect(() => outputRoot(join(root, 'new-output'))).toThrow('checkout');
    expect(() => outputRoot(marker)).toThrow('.git path');
    expect(readFileSync(join(root, 'index.html'), 'utf8')).toBe('index.html');
    rmSync(marker, { recursive: true });
  }
});

test('canonical temp paths work, while symlink ancestors including aliases into authored input are refused', () => {
  const root = directory();
  expect(outputRoot(join(root, 'new-output'))).toBe(join(root, 'new-output'));
  mkdirSync(join(root, 'actual'));
  symlinkSync(join(root, 'actual'), join(root, 'alias'), 'dir');
  expect(() => outputRoot(join(root, 'alias', 'new-output'))).toThrow('canonical realpath');
  symlinkSync(join(ROOT_DIR, 'assets'), join(root, 'source-alias'), 'dir');
  expect(() => outputRoot(join(root, 'source-alias', 'new-output'))).toThrow('canonical realpath');
  // macOS /tmp is an alias to /private/tmp; preserve the explicit canonical-only contract.
  if (realpathSync('/tmp') !== '/tmp') {
    expect(() => outputRoot('/tmp/site-output-path-probe')).toThrow('canonical realpath');
  }
  expect(outputRoot(join(realpathSync('/tmp'), 'site-output-path-probe'))).toBe(join(realpathSync('/tmp'), 'site-output-path-probe'));
});
